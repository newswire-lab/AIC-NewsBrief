SEC = """
#### 8.8.5 关键词标签：本轮自查发现并修掉的 3 处真缺陷

需求 1（热点事件标签改成按事件提炼关键词）此前只做到"能出词"，本轮认真跑数据才发现
**出来的词是垃圾**。三处缺陷都不是读代码看出来的，是**跑真实数据 + 做对照实验**发现的。

**缺陷 1：长度加成把"随便切的一刀"捧成了最高分**

原实现对更长的候选给 `(1 + 0.15*(len-2))` 的加成，理由是"更长的候选更具体"。
**这个理由是错的**：n-gram 越长、全局 df 越低，是组合学上的必然 ——
6 字片段几乎必然只出现一两次，于是**任意一个 6 字滑窗的 IDF 都必然很高**，
再乘上长度加成，就把窗口碎片排到了最前面。实测长标题事件抽出的标签是：

```
「近平总书记引」「领健康中国建」「总书记引领健」「记引领健康中」
```

四段互相错位的滑窗，一段都不是词。**修法**：候选长度收回到 **2~4 字**，
同时**删掉长度加成**。

**缺陷 2：碎片没有被合并回连续短语**

就算切成 2~4 字，滑窗本身仍不是词（「习近平出席」也只是切了两刀）。
但它们在原文里是**挨着的**。**修法**：新增 `_merge_phrase()` ——
`_candidate_spans()` 记录每个候选在原文中的位置，把**相邻/重叠**的入选片段
合并回连续短语。效果：

| 事件标题 | 修复前 | 修复后 |
|---|---|---|
| 习近平经济思想引领中国加快发展新质生产力 | 中国加快发展、习近平经济思、发展新质生产、思想引领中国 | **习近平经济思想引领中国加**、**发展新质生产力** |
| 习近平总书记关切事·长征丨长征精神薪火相传 | 征丨长征精神、长征精神薪火、长征丨长征精、总书记关切事 | **习近平总书记关切事**、**征精神薪火相传**、长征 |
| 就佩戴电子脚镣男子持刀伤人事件 韩国法务部道歉 | 佩戴电子脚镣、国法务部道歉、子持刀伤人事、镣男子 | **就佩戴电子脚镣男子持**、国法务部道 |

**缺陷 3：同一份数据两次跑出不同标签（这是最严重的）**

"标签稳定不抖"正是本项目**不用大模型做标签的核心理由**（见 `keywords.py` 模块文档）。
结果我自己的实现也在抖：**同一个库、同一份数据，连续两次 `tag_all` 给出不同标签**。
根因：候选存在 `set` 里，而 Python 的**字符串哈希每个进程都不一样**
（`PYTHONHASHSEED`），于是下游 `Counter` 的插入顺序跟着变，
排序时**同分并列**的片段就按随机顺序胜出。
**修法**：`_candidates()` 返回**字典序**列表；排序键末尾补上候选字符串本身，
把同分并列变成全序。

**验证方式**（这条必须证明，不能只写在注释里）：用三个不同的 `PYTHONHASHSEED`
各起一个独立进程跑完整 `tag_all`，把 1403 个事件的标签做 JSON 全量比对 ——
**逐字节一致**。

```
seed=0      dumped 1403 tags in 1.3s
seed=1      dumped 1403 tags in 1.2s
seed=99999  dumped 1403 tags in 1.1s
三个 PYTHONHASHSEED 下输出完全一致：True
```

**一次失败的尝试（如实记录）**

修缺陷 2 时，为了不让「新质生产力」被长度上限截出的尾巴「产力」单独成一个标签，
我先写的是"覆盖区间向后推进、把尾巴吞掉"。结果区间**链式蔓延**：
22 字的标题被整条吃光，该事件只剩 1 个标签，13% 的事件掉到 2 个标签以下。
已回退为"超限即丢弃、区间不推进"（不推进就不会蔓延）。
教训：**用"区间扩张"来实现"吞掉多余项"，会牵连到本来不该受影响的范围。**

**顺带修掉的 4 个小问题**

1. **候选跨分隔符生成**：`丨`(U+4E28) 在 Unicode 上属于 CJK 基本区，
   会被 `[\u4e00-\u9fff]+` 当成正文，于是「长征丨总书记关切事」被切出
   「征丨长征精神」这种跨分隔符的碎片。现在先按 `SEPARATORS` 再切一刀。
2. **英文停用词**：修掉了 `publicly`、`screene`（被截断的 screener）、
   `solicitation.`（带尾点）之类；拉丁候选统一 `lower()` 并 `strip(".-–—")`。
   但**展示时保留原文大小写**（`_merge_phrase` 从原文取子串），
   所以标签现在是 `PAC-3`、`PrSM`、`Lockheed` 而不是全小写。
3. **中文虚词表**：补了 `并且/以及/同时/通过/针对…` 等。
   刻意**只收虚词、不收「建设」「发展」这类内容词** ——
   `NOISE` 只屏蔽完全相等的候选，禁止「中国」不会阻止「健康中国建设」被拼出来；
   但禁掉「建设」会让合并少一块拼片，反而拼成「健康中国建」。
4. **文本顺序**：`_doc_text()` 把**标题放到最前面**。原来中文摘要优先，
   遇到中国军网这类整篇稿的源，600 字符全被摘要占满，标题一个字都进不来。

**最终指标**

```
事件 1403 个，空标签 0
标签数分布：4 个 1046（75%）｜3 个 199（14%）｜2 个 149（11%）｜1 个 9（1%）
平均 3.63 个/事件
跨进程确定性：✅ 三个 hash seed 输出完全一致
耗时：全库打标签约 1.2 秒（含 IDF 重建）
```

**遗留局限（写报告时如实说明，不要粉饰）**

没有分词词典，所以**不保证切出来的是词**。当事件只有一篇稿件、
或簇内多篇稿件共用同一标题时，「簇内重复」这个信号退化成了"标题本身"，
此时只能靠"短片段 + 合并"兜住，仍会残留个别碎片（如「生命至」「京出台」）。
彻底解决需要引入分词或边界熵计算，代价与收益不成比例 —— 这是**明确的技术取舍**。
"""

