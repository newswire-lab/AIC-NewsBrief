SEC = """
### 8.11 检索改为关联词扩展；简报允许署名引用（2026-10-14）

#### 8.11.1 问题：检索是字面子串匹配，「俄乌」一条都搜不到

用户反馈：「搜索『俄乌』应该弹出近期所有与俄乌有关的新闻，而不是限制死这两个字，
哪怕是『俄乌冲突』也不行」。**反馈完全成立**：原实现是纯 `LIKE '%词%'`，
而**没有哪篇报道真的写着"俄乌"两个字**。实测：

```
字面含「俄乌」的文章：9 篇
关联词扩展后命中：   100 篇
```

#### 8.11.2 修法：词组内 OR、词组间 AND

`search.RELATED` 把常见新闻实体映射成一组相关词（俄乌 → 乌克兰/俄罗斯/乌军/俄军/
基辅/莫斯科/泽连斯基/顿涅茨克/顿巴斯；巴以 → 以色列/加沙/哈马斯/…）。
`expand_query()` 的命中规则：

1. 词直接命中词表；
2. 否则看**哪个键是它的子串** —— 于是「俄乌冲突」「俄乌局势」也能映射到同一组，
   而不是只能搜字面词（这正是用户点名的那条）；
3. 都不命中则原词单独成组（行为与以前一致，不会把普通词搜坏）。

SQL 结构变成 **组内 OR、组间 AND**：多个关键词仍然要求「都覆盖」，
但每个关键词可以由它的任一关联词满足。评分改为**以词组为单位**：
组内取命中的最高权重、组间相加 —— 「命中越多相关词排得越前」，
又不会因为某个词组词多就把分数堆高。

实测（`--limit 8`）：`俄乌` / `俄乌冲突` / `乌克兰` / `俄罗斯` / `巴以` 均能返回
近期相关新闻，单次 17~73 ms；最近 72 小时窗口内「俄乌」命中 8 条真实相关报道。

界面会显示「🔎 已自动扩展关联词：`俄乌`／`乌克兰`／`俄罗斯`…」，
让用户知道系统替他搜了什么（可解释性，也方便日后加开关）。

#### 8.11.3 简报允许「署名引用多方观点」

用户要求简报能借鉴多家媒体与专家的观点、并标明谁说的。原实现**明确禁止评价**，
且 `verify.SPECULATIVE_WORDS` 把「预计」「分析认为」列为禁用词 ——
**正确的引用句会被判不合格并触发降级**（实测冲突）。已修：

- 校验器只禁**无主推测**（或将/可能会/有望/恐将…），允许带署名的引用；
- 覆盖率计算剔除「据/表示/专家」等**框式词**：引用句覆盖率实测 **0.81**（阈值 0.75），
  以前会被误杀；
- 新增 `brief.extract_viewpoints()`：**先从材料里检索出署名观点句**，单独成块喂给模型
  （不搜出来，小模型只写事实）。实测 3 句里准确挑出 2 句署名观点；
- 提示词要求「导语 → 关键细节 → **各方反应与观点（须写明据谁表示）** → 后续安排」，
  并要求段落间有逻辑承接。

**底线不变**：只能引用**材料里真实存在**的观点，**不得编造机构名与专家姓名**。
**限制如实说明**：29 个源多是 RSS 摘要（中国新闻社一条仅 40~130 字），专家引语本来就少；
且**多机构印证的事件极罕见**（1403 个事件里只有 10 个有 ≥2 家独立机构）。
所以多数事件拿不到「多家媒体口径交叉」。界面已加**如实告知**：
单来源事件显示「本事件只有 1 家机构报道，拿不到多方观点」。
**真正能提升观点密度的做法是抓正文全文**（`parsers_html.py` 已具备能力），列为下一步。
"""

